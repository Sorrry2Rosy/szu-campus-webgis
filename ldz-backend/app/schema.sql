CREATE TABLE IF NOT EXISTS facilities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (length(btrim(name)) > 0),
    category TEXT NOT NULL CHECK (length(btrim(category)) > 0),
    longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    source TEXT NOT NULL,
    is_mock BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS issues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category TEXT NOT NULL CHECK (length(btrim(category)) > 0),
    title TEXT NOT NULL CHECK (length(btrim(title)) > 0),
    description TEXT NOT NULL CHECK (length(btrim(description)) > 0),
    longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    location_description TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'processing', 'resolved')),
    source TEXT NOT NULL DEFAULT 'student'
        CHECK (source IN ('student', 'inspection')),
    note TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp(),
    is_mock BOOLEAN NOT NULL,
    facility_id BIGINT REFERENCES facilities(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_issues_status_category ON issues(status, category);
CREATE INDEX IF NOT EXISTS idx_issues_category_status ON issues(category, status);

CREATE TABLE IF NOT EXISTS building_name_supplements (
    building_key TEXT PRIMARY KEY,
    name TEXT NOT NULL CHECK (length(btrim(name)) > 0),
    annotation_id BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS seed_runs (
    name TEXT PRIMARY KEY
);
